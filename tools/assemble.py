"""Assemble bots/<bot>/src/main.py from bots/<bot>/parts/*.py (sorted by name).

Usage: python -I tools/assemble.py [--bot NAME] [--check] [--split]      (NAME defaults to strat)

The bot ships as ONE file with `import cambc` only (docs/LESSONS.md section 2: every extra
module freezes the champion for rounds on first import). Development happens in numbered parts
so people and agents can work in parallel; this script joins them. Each part may only
`import cambc` (and `from cambc import ...`); any other import fails the build.

Boot fuel [measured 13 Oct]: executing the module's top-level definitions costs ~600 fuel per code line, so
the 7,000-line file booted on round 3. Compiling is free at import but NOT at run time: exec(compile(part))
during play froze champions for 30-150 rounds per part [measured 13 Oct, runs/tzu-s3-a1]. Hence two kinds
of part, chosen by a header line in the part:
    (no header) or `# tzu: eager`   inlined: runs at import (00 base, 10 mem, 20 world, 30 nav, 40 draft, 90 main)
    `# tzu: lazy`                   wrapped in `def _lazy_<name>():` with a `global` statement for every name the
                                    part binds at its top level (symtable), and registered in _LAZY as
                                    (name, code lines, function). The code object is compiled with the file
                                    (free); 90_main calls the functions in name order as setup jobs under the
                                    fuel guard, never in the draft. Calling one defines the part's names as
                                    module globals, exactly as if it had been inlined.
A lazy part may use names of earlier parts at definition time, never of later ones.
--check only verifies the parts and the assembled file compile, without writing.
--split (C4 boot fix, docs/FARM_18OCT.md, 18 Oct): parts 00-89 go to src/bot.py and the 9x parts (the entry) to
src/main.py, which starts by copying bot's names into its own globals. cambc 2.1.6+ pre-imports every module except
main.py before the game (A48), so bot.py's top level (~3-4M fuel for 5.5k lines, measured 18 Oct: round 1 began with
392k) no longer runs on the first play turn. Without --split a stale src/bot.py is removed.
"""
import os
import re
import symtable
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMPORT_RE = re.compile(r"^\s*(import|from)\s+(\S+)", re.M)
MODE_RE = re.compile(r"^# tzu: (eager|lazy)\s*$", re.M)


def code_lines(src):
    """Lines that are not blank or comment-only (the load estimate's unit)."""
    return sum(1 for l in src.splitlines() if l.strip() and not l.strip().startswith("#"))


def bound_names(src, name):
    """Names the part binds at module scope (def, class, assignment, import, for/with/except targets)."""
    top = symtable.symtable(src, name, "exec")
    return sorted(s.get_name() for s in top.get_symbols() if s.is_assigned() or s.is_imported())


def wrap(src, n):
    key = n[:-3]
    fn = f"_lazy_{key}"
    names = bound_names(src, n)
    glb = "".join(f"    global {', '.join(names[i:i + 12])}\n" for i in range(0, len(names), 12))
    body = "".join(("    " + l) if l.strip() else l for l in src.rstrip().splitlines(True))
    return (f"# ---- {n} (lazy: runs when 90_main calls {fn}) ----\ndef {fn}():\n{glb}{body}\n\n\n"
            f"_LAZY.append(({key!r}, {code_lines(src)}, {fn}))\n")


def main():
    check = "--check" in sys.argv
    split = "--split" in sys.argv
    bot = "strat"
    if "--bot" in sys.argv:
        i = sys.argv.index("--bot")
        if i + 1 >= len(sys.argv):
            sys.exit("--bot needs a name")
        bot = sys.argv[i + 1]
    PARTS = os.path.join(ROOT, "bots", bot, "parts")
    OUT = os.path.join(ROOT, "bots", bot, "src", "main.py")
    if not os.path.isdir(PARTS):
        sys.exit(f"no parts folder {PARTS}")
    names = sorted(n for n in os.listdir(PARTS) if n.endswith(".py"))
    chunks = ["_LAZY = []    # lazy parts: (name, code lines, loader); 90_main calls them in this order\n"]
    lazy = []
    for n in names:
        src = open(os.path.join(PARTS, n), encoding="utf-8").read()
        for m in IMPORT_RE.finditer(src):
            mod = m.group(2).split(".")[0]
            if mod != "cambc":
                sys.exit(f"{n}: forbidden import of {mod!r} (only cambc is allowed)")
        compile(src, n, "exec")
        mm = MODE_RE.search(src[:400])
        if mm is not None and mm.group(1) == "lazy":
            lazy.append(n[:-3])
            chunks.append(wrap(src, n))
        else:
            chunks.append(f"# ---- {n} ----\n{src.rstrip()}\n")
    head = f"# GENERATED by tools/assemble.py from bots/{bot}/parts/*.py. Do not edit by hand.\n\n"
    BOT = os.path.join(os.path.dirname(OUT), "bot.py")
    if split:
        k = next((i for i, n in enumerate(names) if n.startswith("9")), len(names))
        lib = head + "\n".join(chunks[:k + 1])
        out = (head + "import cambc\nimport bot as _bot\n\n"
               "globals().update({k: v for k, v in vars(_bot).items() if not k.startswith('__')})   # one namespace\n\n"
               + "\n".join(chunks[k + 1:]))
        compile(lib, "bot.py", "exec")
    else:
        out = head + "\n".join(chunks)
    compile(out, "main.py", "exec")
    if not check:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        open(OUT, "w", encoding="utf-8", newline="\n").write(out)
        if split:
            open(BOT, "w", encoding="utf-8", newline="\n").write(lib)
        elif os.path.isfile(BOT):
            os.remove(BOT)
    print(f"{'checked' if check else 'wrote'} {OUT}{' + bot.py' if split else ''} from {len(names)} parts "
          f"({len(lazy)} lazy: {', '.join(lazy)}); {out.count(chr(10)) + (lib.count(chr(10)) if split else 0)} lines")


if __name__ == "__main__":
    main()
